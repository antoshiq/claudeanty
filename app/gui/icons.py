@lru_cache(maxsize=256)
def icon(name: str, color: str = "#cccccc", size: int = 16) -> QIcon:
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="{color}" '
           f'stroke-width="1.6" stroke-linecap="round" stroke-linejoin="round">{_P[name]}</svg>')
    if name in ("play", "stop"):
        svg = svg.replace('fill="none"', f'fill="{color}"', 1)
    r = QSvgRenderer(QByteArray(svg.encode()))
    ico = QIcon()
    for scale in (1, 2):
        pm = QPixmap(size * scale, size * scale)
        pm.fill(Qt.transparent)
        p = QPainter(pm)
        p.setRenderHint(QPainter.Antialiasing)
        r.render(p, QRectF(0, 0, size * scale, size * scale))
        p.end()
        pm.setDevicePixelRatio(scale)
        ico.addPixmap(pm)
    return ico


def svg_file(name: str, color: str, path) -> str:
    """Сохраняет иконку как .svg-файл (нужно для QSS: стрелки комбобоксов, галочки)."""
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="{color}" '
           f'stroke-width="2.4" stroke-linecap="round" stroke-linejoin="round">{_P[name]}</svg>')
    path.write_text(svg, encoding="utf-8")
    return path.as_posix()
